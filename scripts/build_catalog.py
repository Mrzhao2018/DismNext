def load_en_map(path: Path) -> dict[str, str]:
    raw = path.read_text(encoding="utf-8")
    # Fix unescaped '&' in en.xml attributes (e.g., line 1019)
    sanitized = re.sub(
        r"&(?!amp;|lt;|gt;|quot;|apos;|#\d+;|#x[0-9a-fA-F]+;)",
        "&amp;",
        raw,
    )
    root = ET.fromstring(sanitized)
    mapping: dict[str, str] = {}
    sm = root.find("StringMaps")
    if sm is not None:
        for el in sm.findall("String"):
            target = (el.get("Target") or "").strip()
            link = (el.get("Link") or "").strip()
            if target and link:
                mapping[target] = link
    mapping.update(EXTRA_EN)
    return mapping


def strip_hash(s: str | None) -> str:
    if not s:
        return ""
    s = s.strip()
    if s.startswith("#"):
        return s[1:].strip()
    return s


def loc(s: str | None, en_map: dict[str, str]) -> dict[str, str]:
    zh = strip_hash(s)
    if not zh:
        return {"zh": "", "en": ""}
    en = en_map.get(zh) or en_map.get(zh.replace("\u00a0", " ")) or zh
    return {"zh": zh, "en": en}


def parse_bool_attr(val: str | None) -> bool:
    return (val or "").strip().lower() == "true"


def parse_condition_node(el: ET.Element) -> dict[str, Any]:
    tag = el.tag
    txt = (el.text or "").strip()
    if tag == "True":
        return {"type": "True"}
    if tag == "False":
        return {"type": "False"}
    if tag == "And":
        return {"type": "And", "children": [parse_condition_node(c) for c in el]}
    if tag == "Or":
        return {"type": "Or", "children": [parse_condition_node(c) for c in el]}
    if tag == "Not":
        return {"type": "Not", "children": [parse_condition_node(c) for c in el]}
    if tag == "OSVersion":
        return {
            "type": "OSVersion",
            "compare": el.get("Compare") or "==",
            "version": txt,
        }
    if tag == "FileExist":
        return {
            "type": "FileExist",
            "file_path": el.get("FilePath") or "",
            "wow64": el.get("Wow64") or None,
        }
    if tag == "FileVersion":
        fp = el.get("FilePath") or ""
        # Clean-room replacement: remove dependency on legacy NCleaner.dll binary
        if "ncleaner.dll" in fp.lower():
            return {"type": "True"}
        return {
            "type": "FileVersion",
            "file_path": fp,
            "compare": el.get("Compare") or ">=",
            "version": txt,
        }
    if tag == "ImageFlags":
        mask = int(txt, 16) if txt else 0
        return {"type": "ImageFlags", "mask": mask}
    if tag == "Arch":
        return {"type": "Arch", "arch": int(txt) if txt else 0}
    if tag == "RegExist":
        return {
            "type": "RegExist",
            "key": el.get("Key") or "",
            "value": el.get("Value"),
            "reg_type": el.get("Type"),
            "data": el.get("Data"),
            "compare": el.get("Compare"),
            "wow64": el.get("Wow64"),
        }
    if tag == "QueryServiceStart":
        return {
            "type": "QueryServiceStart",
            "name": el.get("Name") or "",
            "start_type": int(el.get("Type") or "0"),
        }
    raise ValueError(f"Unsupported condition tag: {tag}")


def parse_applicable(el: ET.Element | None) -> dict[str, Any]:
    if el is None or len(el) == 0:
        return {"type": "True"}
    if len(el) == 1:
        return parse_condition_node(el[0])
    return {"type": "And", "children": [parse_condition_node(c) for c in el]}


def parse_action(el: ET.Element) -> dict[str, Any]:
    tag = el.tag
    if tag == "General":
        queries = [
            (q.text or "").strip().rstrip("`")
            for q in el.findall("Query")
            if (q.text or "").strip()
        ]
        excluded = [
            (ex.text or "").strip().rstrip("`")
            for ex in el.findall("Excluded")
            if (ex.text or "").strip()
        ]
        return {
            "type": "General",
            "root_path": (el.get("RootPath") or "").strip(),
            "flags": el.get("Flags") or "Directory|File",
            "id": el.get("ID") or None,
            "queries": queries,
            "excluded": excluded,
        }
    if tag == "Custom":
        return {
            "type": "Custom",
            "proc_name": el.get("ProcName") or "",
            "flags": el.get("Flags") or None,
        }
    if tag == "RegWrite":
        return {
            "type": "RegWrite",
            "key": el.get("Key") or "",
            "value": el.get("Value"),
            "reg_type": el.get("Type") or None,
            "data": el.get("Data"),
            "operator": el.get("Operator") or "=",
            "wow64": el.get("Wow64") or None,
            "fun": parse_bool_attr(el.get("Fun")),
        }
    if tag == "RegDelete":
        skip = el.get("SkipError")
        return {
            "type": "RegDelete",
            "key": el.get("Key") or "",
            "value": el.get("Value"),
            "reg_type": el.get("Type") or None,
            "data": el.get("Data"),
            "skip_error": int(skip) if skip is not None else None,
            "wow64": el.get("Wow64") or None,
        }
    if tag == "RegMove":
        skip = el.get("SkipError")
        return {
            "type": "RegMove",
            "key": el.get("Key") or "",
            "new_key": el.get("NewKey") or "",
            "value": el.get("Value"),
            "new_value": el.get("NewValue"),
            "skip_error": int(skip) if skip is not None else None,
            "wow64": el.get("Wow64") or None,
        }
    if tag == "SetServiceStart":
        return {
            "type": "SetServiceStart",
            "name": el.get("Name") or "",
            "start_type": int(el.get("Type") or "3"),
        }
    if tag == "ExplorerNotify":
        return {
            "type": "ExplorerNotify",
            "notify_type": el.get("Type") or "",
            "msg": el.get("msg"),
            "w_param": el.get("wParam"),
            "l_param": el.get("lParam"),
            "cmd": el.get("Cmd"),
            "explorer": parse_bool_attr(el.get("Explorer")),
        }
    if tag == "FileCreateByZIP":
        return {
            "type": "FileCreateByZIP",
            "path": el.get("Path") or "",
            "zip_file": el.get("ZIPFile") or "",
        }
    raise ValueError(f"Unsupported action tag: {tag}")


def parse_activate(el: ET.Element | None) -> tuple[list[dict[str, Any]], bool, str | None]:
    if el is None:
        return [], False, None
    actions = [parse_action(c) for c in el]
    rescan = parse_bool_attr(el.get("Rescan"))
    restart = el.get("Restart")
    return actions, rescan, restart


def parse_scan(el: ET.Element, en_map: dict[str, str]) -> dict[str, Any]:
    work_str = el.get("Work")
    named_apps: dict[str, Any] = {}
    for child in el:
        if child.tag.startswith("Applicable_"):
            named_apps[child.tag] = parse_applicable(child)
    actions, rescan, restart = parse_activate(el.find("Activate"))
    name_el = el.find("Name")
    desc_el = el.find("Description")
    warn_el = el.find("Warning")
    return {
        "work": int(work_str) if work_str and work_str.isdigit() else 1,
        "scan_type": el.get("Type") or None,
        "name_override": loc(name_el.text, en_map) if name_el is not None else None,
        "description_override": loc(desc_el.text, en_map) if desc_el is not None else None,
        "warning_override": loc(warn_el.text, en_map) if warn_el is not None else None,
        "applicable": parse_applicable(el.find("Applicable")),
        "named_applicables": named_apps,
        "actions": actions,
        "rescan": rescan,
        "restart": restart,
    }


def parse_cleanup_item(
    el: ET.Element, en_map: dict[str, str], idx: int, source: str
) -> dict[str, Any]:
    raw_name = strip_hash(el.get("Name"))
    level = int(el.get("Level") or "2")
    work_str = el.get("Work")
    group_txt = el.findtext("Group") or "其他"
    desc_txt = el.findtext("Description") or ""
    warn_txt = el.findtext("Warning") or ""

    scans: list[dict[str, Any]] = []
    s = el.find("Scan")
    if s is not None:
        scans.append(parse_scan(s, en_map))
    sc = el.find("ScanCollection")
    if sc is not None:
        for s2 in sc.findall("Scan"):
            scans.append(parse_scan(s2, en_map))

    rule: dict[str, Any] = {
        "id": f"clean-{idx:03d}",
        "name": loc(raw_name, en_map),
        "group": loc(group_txt, en_map),
        "description": loc(desc_txt, en_map),
        "warning": loc(warn_txt, en_map) if warn_txt.strip() else None,
        "level": level,
        "work": int(work_str) if work_str and work_str.isdigit() else None,
        "source": source,
        "scans": scans,
    }

    # Modernization fix #2: Merge v3-cache into NuGet rule
    if raw_name == "NuGet包缓存":
        rule["description"] = loc(
            "引用了NuGet包的.NET应用程序在使用Visual Studio生成时产生的缓存（含 v3-cache 与 .nuget 缓存）。",
            en_map,
        )
        rule["scans"] = [
            {
                "work": 1,
                "scan_type": None,
                "name_override": None,
                "description_override": None,
                "warning_override": None,
                "applicable": {
                    "type": "Or",
                    "children": [
                        {"type": "FileExist", "file_path": "%USERPROFILE%\\.nuget", "wow64": None},
                        {"type": "FileExist", "file_path": "%LOCALAPPDATA%\\NuGet\\v3-cache", "wow64": None},
                    ],
                },
                "named_applicables": {
                    "Applicable_1": {"type": "FileExist", "file_path": "%USERPROFILE%\\.nuget", "wow64": None},
                    "Applicable_2": {"type": "FileExist", "file_path": "%LOCALAPPDATA%\\NuGet\\v3-cache", "wow64": None},
                },
                "actions": [
                    {
                        "type": "General",
                        "root_path": "%USERPROFILE%\\.nuget",
                        "flags": "Directory|File",
                        "id": "Applicable_1",
                        "queries": [],
                        "excluded": [],
                    },
                    {
                        "type": "General",
                        "root_path": "%LOCALAPPDATA%\\NuGet\\v3-cache",
                        "flags": "Directory|File",
                        "id": "Applicable_2",
                        "queries": [],
                        "excluded": [],
                    },
                ],
                "rescan": False,
                "restart": None,
            }
        ]

    # Modernization fix #3: Downgrade overly broad %ProgramData%\temp rule
    if raw_name == "腾讯相关软件下载目录":
        rule["name"] = loc("ProgramData 通用临时目录（原腾讯下载目录）", en_map)
        rule["description"] = loc(
            "原规则名标注为腾讯下载残留，但实际扫描通用的 %ProgramData%\\temp 目录，可能包含其他软件临时文件，已降级为谨慎清理。",
            en_map,
        )
        rule["warning"] = loc(
            "此操作将清空整个 %ProgramData%\\temp 目录，请确认无安装程序正在运行。",
            en_map,
        )
        rule["level"] = 1

    return rule


def parse_scope(scope_el: ET.Element | None, item_type: str, en_map: dict[str, str]) -> dict[str, Any] | None:
    if scope_el is None:
        return None
    if item_type == "CheckBox":
        st = scope_el.find("State")
        tr = scope_el.find("True")
        fa = scope_el.find("False")
        tr_acts, tr_rescan, tr_restart = parse_activate(tr.find("Activate") if tr is not None else None)
        fa_acts, fa_rescan, fa_restart = parse_activate(fa.find("Activate") if fa is not None else None)
        w_true = tr.findtext("Warning") if tr is not None else None
        w_false = fa.findtext("Warning") if fa is not None else None
        return {
            "kind": "checkbox",
            "state": parse_applicable(st.find("Applicable") if st is not None else None),
            "true_actions": tr_acts,
            "true_warning": loc(w_true, en_map) if w_true and w_true.strip() else None,
            "true_restart": tr_restart,
            "false_actions": fa_acts,
            "false_warning": loc(w_false, en_map) if w_false and w_false.strip() else None,
            "false_restart": fa_restart,
        }
    else:
        dropdowns = []
        for dd in scope_el.findall("Dropdown"):
            acts, _, restart = parse_activate(dd.find("Activate"))
            w = dd.findtext("Warning")
            dropdowns.append(
                {
                    "name": loc(dd.get("Name"), en_map),
                    "applicable": parse_applicable(dd.find("Applicable")),
                    "actions": acts,
                    "warning": loc(w, en_map) if w and w.strip() else None,
                    "restart": restart,
                }
            )
        return {"kind": "combo", "dropdowns": dropdowns}


def build_catalog() -> dict[str, Any]:
    en_map = load_en_map(EN_XML)
    main_root = ET.parse(MAIN_XML).getroot()
    custom_root = ET.parse(CUSTOM_XML).getroot()

    # 1. Cleanup rules
    cleanup_rules: list[dict[str, Any]] = []
    idx = 1
    for item_el in main_root.find("CleanCollection4").findall("Item"):
        cleanup_rules.append(parse_cleanup_item(item_el, en_map, idx, "official-1002.2"))
        idx += 1

    for item_el in custom_root.find("CleanCollection4").findall("Item"):
        name = strip_hash(item_el.get("Name"))
        # Already merged into NuGet 包缓存
        if name == "NuGet v3 包缓存":
            continue
        cleanup_rules.append(parse_cleanup_item(item_el, en_map, idx, "win11-modern"))
        idx += 1

    # 2. System optimization groups
    opt_groups: list[dict[str, Any]] = []
    group_by_zh: dict[str, dict[str, Any]] = {}
    opt_idx = 1

    def ingest_opt_section(sec: ET.Element, source: str) -> None:
        nonlocal opt_idx
        for g_el in sec.findall("Group"):
            g_zh = strip_hash(g_el.get("Name"))
            if g_zh not in group_by_zh:
                grp = {
                    "id": f"grp-{len(opt_groups) + 1:02d}",
                    "name": loc(g_zh, en_map),
                    "applicable": parse_applicable(g_el.find("Applicable")),
                    "items": [],
                }
                group_by_zh[g_zh] = grp
                opt_groups.append(grp)
            else:
                grp = group_by_zh[g_zh]

            for it_el in g_el.findall("Item"):
                it_type = it_el.get("Type") or "CheckBox"
                grp["items"].append(
                    {
                        "id": f"opt-{opt_idx:03d}",
                        "name": loc(it_el.get("Name"), en_map),
                        "item_type": it_type,
                        "source": source,
                        "applicable": parse_applicable(it_el.find("Applicable")),
                        "current": parse_scope(it_el.find("Current"), it_type, en_map),
                        "default": parse_scope(it_el.find("Default"), it_type, en_map),
                        "system": parse_scope(it_el.find("System"), it_type, en_map),
                    }
                )
                opt_idx += 1

    ingest_opt_section(main_root.find("SystemOptimization"), "official-1002.2")
    ingest_opt_section(custom_root.find("SystemOptimization"), "win11-modern")

    return {
        "schema_version": 1,
        "base_version": "10.1.1002.2+win11",
        "cleanup_rules": cleanup_rules,
        "optimization_groups": opt_groups,
    }


def main() -> None:
    catalog = build_catalog()
    OUT_JSON.parent.mkdir(parents=True, exist_ok=True)
    serialized = json.dumps(catalog, ensure_ascii=False, indent=2)
    assert "`" not in serialized, "Unexpected backtick remained in compiled rules!"
    OUT_JSON.write_text(serialized, encoding="utf-8", newline="\n")

    n_clean = len(catalog["cleanup_rules"])
    n_groups = len(catalog["optimization_groups"])
    n_opt = sum(len(g["items"]) for g in catalog["optimization_groups"])
    untranslated_clean = sum(
        1 for r in catalog["cleanup_rules"] if r["name"]["zh"] == r["name"]["en"]
    )
    untranslated_opt = sum(
        1
        for g in catalog["optimization_groups"]
        for i in g["items"]
        if i["name"]["zh"] == i["name"]["en"]
    )
    print(f"Wrote {OUT_JSON} ({len(serialized)} bytes)")
    print(f"Cleanup rules: {n_clean} (identical zh/en names: {untranslated_clean})")
    print(f"Optimization groups: {n_groups}, items: {n_opt} (identical zh/en names: {untranslated_opt})")


if __name__ == "__main__":
    main()
